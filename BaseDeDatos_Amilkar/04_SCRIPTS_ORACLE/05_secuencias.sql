-- EcoAccess BD — 05 · Secuencias
-- Ejecutar como ECOACCESS_BD (F5). Solo consulta: no crea nada.
--
-- ¿Por qué el modelo EcoAccess NO crea secuencias a mano?
--   Todas sus claves primarias son IDENTITY (igual que P3). Oracle crea
--   y administra por dentro una secuencia por cada columna IDENTITY
--   (se llaman ISEQ$$_nnnnn). Crear además SEQUENCE + TRIGGER para las
--   mismas tablas sería duplicar el mecanismo.
--
-- La técnica clásica SEQUENCE + TRIGGER BEFORE INSERT que pide la tarea
-- se practica en una tabla académica propia, en el esquema separado
-- ECOACCESS_PRACTICAS: 05_SQL_Y_PLSQL/00_PRACTICAS_VERIFICADAS/P01_secuencia_pk.sql.
-- =====================================================================
SET LINESIZE 200
COLUMN table_name    FORMAT A28
COLUMN column_name   FORMAT A24
COLUMN generation_type FORMAT A12
COLUMN sequence_name FORMAT A20

PROMPT ==== Columnas IDENTITY del modelo y su secuencia interna ====
SELECT table_name, column_name, generation_type, sequence_name
FROM   user_tab_identity_cols
ORDER  BY table_name;

PROMPT ==== Secuencias del esquema (todas deben ser ISEQ$$ internas) ====
SELECT sequence_name, min_value, increment_by, cache_size, last_number
FROM   user_sequences
ORDER  BY sequence_name;
