-- =====================================================================
-- EcoAccess BD (prof. Amílkar) — 02 · Tablas
-- Ejecutar conectado como ECOACCESS_BD (F5), después de 00 y 01.
--
-- Crea las 19 tablas del modelo con su clave primaria, columnas
-- obligatorias (NOT NULL) y valores por defecto (DEFAULT).
-- Las claves foráneas, únicas y CHECK van en 03_restricciones.sql para
-- poder explicarlas por separado en clase.
--
-- Protección: si ya existen las 19 tablas se detiene (ORA-20010);
-- si existe solo una parte se detiene (ORA-20011) y remite al plan de
-- reversión. Nunca borra nada.
--
-- Convenciones (las mismas de EcoAccess P3):
--   * Textos VARCHAR2(n CHAR): n cuenta caracteres, no bytes (tildes).
--   * Sí/No en NUMBER(1) con CHECK (0,1).
--   * Fechas en TIMESTAMP con hora UTC (sufijo _utc). Se convierten a
--     America/Bogota solo al consultar.
--   * Códigos numéricos iguales a los enum de C# de P3.
--   * Claves primarias IDENTITY (Oracle genera el número).
--   * Sin ON DELETE CASCADE: el historial no se borra en cadena.
-- =====================================================================
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    v_existentes NUMBER;
BEGIN
    IF USER <> 'ECOACCESS_BD' THEN
        RAISE_APPLICATION_ERROR(-20009, 'Conéctate como ECOACCESS_BD. Usuario actual: ' || USER);
    END IF;
    SELECT COUNT(*) INTO v_existentes FROM user_tables
    WHERE table_name IN ('ROL','USUARIO','USUARIO_ROL','CREDENCIAL_ACCESO','VINCULO_TELEGRAM',
        'PUNTO_INSTALACION','CONTENEDOR','MATERIAL','CONTENEDOR_MATERIAL','PESO_REFERENCIAL',
        'INTERACCION','CONSULTA_VISION','ORDEN_APERTURA','EVENTO_DISPOSITIVO','DEPOSITO',
        'REGLA_ECOPUNTOS','MOVIMIENTO_ECOPUNTOS','AUDITORIA_DEPOSITO','HISTORIAL_ESTADO_CONTENEDOR');
    IF v_existentes = 19 THEN
        RAISE_APPLICATION_ERROR(-20010, 'Las 19 tablas ya existen. No se modificó nada.');
    ELSIF v_existentes > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Instalación parcial (' || v_existentes
            || ' de 19). No se modificó nada; revisa 99_PLAN_REVERSION.md.');
    END IF;
END;
/

-- ------------------------------------------------------------------
-- MÓDULO SEGURIDAD
-- ------------------------------------------------------------------
-- 1. ROL: los tres roles de negocio (catálogo cerrado).
CREATE TABLE rol (
    id_rol        NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    codigo        NUMBER(2)           NOT NULL,
    descripcion   VARCHAR2(200 CHAR)  NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (id_rol)
);

-- 2. USUARIO: una persona (ciudadano, operario o administrador).
CREATE TABLE usuario (
    id_usuario                NUMBER(10)          GENERATED ALWAYS AS IDENTITY,
    nombre                    VARCHAR2(100 CHAR)  NOT NULL,
    correo_electronico        VARCHAR2(254 CHAR)  NOT NULL,
    fecha_registro_utc        TIMESTAMP           DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    activo                    NUMBER(1)           DEFAULT 1 NOT NULL,
    version_consentimiento    VARCHAR2(20 CHAR),
    fecha_consentimiento_utc  TIMESTAMP,
    es_sintetico              NUMBER(1)           DEFAULT 0 NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario)
);

-- 3. USUARIO_ROL: relación muchos a muchos entre USUARIO y ROL.
CREATE TABLE usuario_rol (
    id_usuario            NUMBER(10)  NOT NULL,
    id_rol                NUMBER(10)  NOT NULL,
    fecha_asignacion_utc  TIMESTAMP   DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_usuario_rol PRIMARY KEY (id_usuario, id_rol)
);

-- 4. CREDENCIAL_ACCESO: contraseña de la aplicación de escritorio, solo como hash.
CREATE TABLE credencial_acceso (
    id_usuario           NUMBER(10)  NOT NULL,
    hash_contrasena      RAW(32)     NOT NULL,
    sal                  RAW(16)     NOT NULL,
    iteraciones          NUMBER(7)   NOT NULL,
    intentos_fallidos    NUMBER(3)   DEFAULT 0 NOT NULL,
    bloqueada_hasta_utc  TIMESTAMP,
    fecha_cambio_utc     TIMESTAMP   DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_credencial_acceso PRIMARY KEY (id_usuario)
);

-- 5. VINCULO_TELEGRAM: une la cuenta EcoAccess con la cuenta de Telegram.
CREATE TABLE vinculo_telegram (
    id_vinculo         NUMBER(10)  GENERATED ALWAYS AS IDENTITY,
    id_usuario         NUMBER(10)  NOT NULL,
    telegram_user_id   NUMBER(19)  NOT NULL,
    fecha_vinculo_utc  TIMESTAMP   DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    fecha_baja_utc     TIMESTAMP,
    CONSTRAINT pk_vinculo_telegram PRIMARY KEY (id_vinculo)
);

-- ------------------------------------------------------------------
-- MÓDULO INFRAESTRUCTURA Y CATÁLOGO
-- ------------------------------------------------------------------
-- 6. PUNTO_INSTALACION: la estación (lugar con hasta tres canecas).
CREATE TABLE punto_instalacion (
    id_punto_instalacion  NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre                VARCHAR2(100 CHAR)  NOT NULL,
    referencia_ubicacion  VARCHAR2(200 CHAR),
    codigo_qr_estacion    VARCHAR2(64 CHAR),
    activo                NUMBER(1)           DEFAULT 1 NOT NULL,
    es_sintetico          NUMBER(1)           DEFAULT 0 NOT NULL,
    CONSTRAINT pk_punto_instalacion PRIMARY KEY (id_punto_instalacion)
);

-- 7. CONTENEDOR: una caneca de color (VERDE, BLANCA o NEGRA).
CREATE TABLE contenedor (
    id_contenedor              NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_punto_instalacion       NUMBER(10)          NOT NULL,
    nombre                     VARCHAR2(100 CHAR)  NOT NULL,
    categoria                  NUMBER(1)           NOT NULL,
    identificador_qr           VARCHAR2(64 CHAR),
    identificador_dispositivo  VARCHAR2(40 CHAR),
    fecha_alta_utc             TIMESTAMP           DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    estado                     NUMBER(1)           DEFAULT 2 NOT NULL,
    CONSTRAINT pk_contenedor PRIMARY KEY (id_contenedor)
);

-- 8. MATERIAL: catálogo validado con el que se contrasta lo que dice la IA.
CREATE TABLE material (
    id_material   NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    codigo        VARCHAR2(30 CHAR)   NOT NULL,
    nombre        VARCHAR2(100 CHAR)  NOT NULL,
    categoria     NUMBER(1)           NOT NULL,
    descripcion   VARCHAR2(500 CHAR),
    habilitado    NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT pk_material PRIMARY KEY (id_material)
);

-- 9. CONTENEDOR_MATERIAL: qué materiales recibe cada caneca (N:M).
--    La categoría se repite a propósito para que dos FK compuestas
--    garanticen que el material y la caneca son del mismo color.
CREATE TABLE contenedor_material (
    id_contenedor  NUMBER(10)  NOT NULL,
    id_material    NUMBER(10)  NOT NULL,
    categoria      NUMBER(1)   NOT NULL,
    CONSTRAINT pk_contenedor_material PRIMARY KEY (id_contenedor, id_material)
);

-- 10. PESO_REFERENCIAL: peso típico de un objeto para ESTIMAR (no medir).
CREATE TABLE peso_referencial (
    id_peso_referencial  NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_material          NUMBER(10)          NOT NULL,
    clave_objeto         VARCHAR2(40 CHAR)   NOT NULL,
    descripcion_objeto   VARCHAR2(150 CHAR)  NOT NULL,
    estado_visual        NUMBER(1)           DEFAULT 0 NOT NULL,
    gramos_minimo        NUMBER(8,1)         NOT NULL,
    gramos_tipico        NUMBER(8,1)         NOT NULL,
    gramos_maximo        NUMBER(8,1)         NOT NULL,
    fuente               VARCHAR2(200 CHAR)  NOT NULL,
    CONSTRAINT pk_peso_referencial PRIMARY KEY (id_peso_referencial)
);

-- ------------------------------------------------------------------
-- MÓDULO OPERACIÓN (flujo QR → foto → orden → evento → depósito)
-- ------------------------------------------------------------------
-- 11. INTERACCION: una sesión iniciada al escanear el QR (o manual).
CREATE TABLE interaccion (
    id_interaccion          NUMBER(10)          GENERATED ALWAYS AS IDENTITY,
    id_punto_instalacion    NUMBER(10)          NOT NULL,
    id_contenedor           NUMBER(10),
    id_usuario              NUMBER(10),
    canal                   NUMBER(1)           NOT NULL,
    estado                  NUMBER(1)           DEFAULT 1 NOT NULL,
    id_material_sugerido    NUMBER(10),
    confianza_sugerida      NUMBER(4,3),
    id_material_confirmado  NUMBER(10),
    cantidad_declarada      NUMBER(4),
    id_operario             NUMBER(10),
    motivo                  VARCHAR2(300 CHAR),
    fecha_inicio_utc        TIMESTAMP           DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    fecha_cierre_utc        TIMESTAMP,
    es_sintetico            NUMBER(1)           DEFAULT 0 NOT NULL,
    CONSTRAINT pk_interaccion PRIMARY KEY (id_interaccion)
);

-- 12. CONSULTA_VISION: una foto analizada por Eco. NO es un depósito.
CREATE TABLE consulta_vision (
    id_consulta             NUMBER(10)          GENERATED ALWAYS AS IDENTITY,
    clave                   VARCHAR2(80 CHAR)   NOT NULL,
    id_usuario              NUMBER(10),
    id_interaccion          NUMBER(10),
    canal                   NUMBER(2)           NOT NULL,
    modo                    NUMBER(2)           NOT NULL,
    proveedor               VARCHAR2(80 CHAR)   NOT NULL,
    modelo                  VARCHAR2(80 CHAR),
    resultado               NUMBER(2)           NOT NULL,
    clave_objeto            VARCHAR2(40 CHAR),
    id_material             NUMBER(10),
    unidades_estimadas      NUMBER(4),
    estado_visual           NUMBER(1),
    id_peso_referencial     NUMBER(10),
    peso_estimado_kg        NUMBER(9,4),
    admision                NUMBER(2),
    id_contenedor_sugerido  NUMBER(10),
    latencia_ms             NUMBER(7)           NOT NULL,
    fecha_utc               TIMESTAMP           DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    es_sintetico            NUMBER(1)           DEFAULT 0 NOT NULL,
    CONSTRAINT pk_consulta_vision PRIMARY KEY (id_consulta)
);

-- 13. ORDEN_APERTURA: la orden de abrir UNA caneca (idempotente).
CREATE TABLE orden_apertura (
    id_orden               NUMBER(10)         GENERATED ALWAYS AS IDENTITY,
    id_interaccion         NUMBER(10)         NOT NULL,
    id_contenedor          NUMBER(10)         NOT NULL,
    clave_idempotencia     VARCHAR2(64 CHAR)  NOT NULL,
    estado                 NUMBER(1)          DEFAULT 1 NOT NULL,
    fecha_emision_utc      TIMESTAMP          DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    fecha_vencimiento_utc  TIMESTAMP          NOT NULL,
    fecha_cierre_utc       TIMESTAMP,
    CONSTRAINT pk_orden_apertura PRIMARY KEY (id_orden)
);

-- 14. EVENTO_DISPOSITIVO: lo que informa la caneca (o el simulador).
CREATE TABLE evento_dispositivo (
    id_evento              NUMBER(10)         GENERATED ALWAYS AS IDENTITY,
    id_contenedor          NUMBER(10)         NOT NULL,
    id_externo             VARCHAR2(64 CHAR)  NOT NULL,
    tipo                   NUMBER(1)          NOT NULL,
    id_orden               NUMBER(10),
    resultado              NUMBER(1)          NOT NULL,
    fecha_dispositivo_utc  TIMESTAMP,
    fecha_recepcion_utc    TIMESTAMP          DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_evento_dispositivo PRIMARY KEY (id_evento)
);

-- 15. DEPOSITO: un residuo que (según sensor o declaración) entró en la caneca,
--     y su verificación independiente por un operario o administrador.
CREATE TABLE deposito (
    id_deposito             NUMBER(10)          GENERATED ALWAYS AS IDENTITY,
    id_orden                NUMBER(10)          NOT NULL,
    id_evento               NUMBER(10)          NOT NULL,
    sin_sensor              NUMBER(1)           DEFAULT 0 NOT NULL,
    id_material_declarado   NUMBER(10)          NOT NULL,
    cantidad_declarada      NUMBER(4),
    peso_estimado_kg        NUMBER(9,4),
    id_peso_referencial     NUMBER(10),
    estado_verificacion     NUMBER(1)           DEFAULT 0 NOT NULL,
    id_material_verificado  NUMBER(10),
    cantidad_verificada     NUMBER(4),
    id_verificador          NUMBER(10),
    fecha_verificacion_utc  TIMESTAMP,
    motivo_verificacion     VARCHAR2(300 CHAR),
    peso_medido_kg          NUMBER(9,4),
    instrumento_medicion    VARCHAR2(60 CHAR),
    precision_medicion_g    NUMBER(6,1),
    fecha_deteccion_utc     TIMESTAMP           NOT NULL,
    CONSTRAINT pk_deposito PRIMARY KEY (id_deposito)
);

-- ------------------------------------------------------------------
-- MÓDULO INCENTIVOS (EcoPuntos)
-- ------------------------------------------------------------------
-- 16. REGLA_ECOPUNTOS: tarifa versionada por material.
CREATE TABLE regla_ecopuntos (
    id_regla      NUMBER(10)          GENERATED ALWAYS AS IDENTITY,
    id_material   NUMBER(10)          NOT NULL,
    puntos        NUMBER(7)           NOT NULL,
    por_unidad    NUMBER(1)           DEFAULT 0 NOT NULL,
    descripcion   VARCHAR2(200 CHAR)  NOT NULL,
    desde_utc     TIMESTAMP           NOT NULL,
    hasta_utc     TIMESTAMP,
    id_creador    NUMBER(10)          NOT NULL,
    creada_utc    TIMESTAMP           DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    es_sintetica  NUMBER(1)           DEFAULT 0 NOT NULL,
    CONSTRAINT pk_regla_ecopuntos PRIMARY KEY (id_regla)
);

-- 17. MOVIMIENTO_ECOPUNTOS: libro contable (créditos y reversos, nunca se borra).
CREATE TABLE movimiento_ecopuntos (
    id_movimiento            NUMBER(10)          GENERATED ALWAYS AS IDENTITY,
    clave_idempotencia       VARCHAR2(80 CHAR)   NOT NULL,
    tipo                     NUMBER(1)           NOT NULL,
    id_deposito              NUMBER(10)          NOT NULL,
    id_usuario               NUMBER(10)          NOT NULL,
    id_regla                 NUMBER(10)          NOT NULL,
    puntos                   NUMBER(8)           NOT NULL,
    id_movimiento_revertido  NUMBER(10),
    id_actor                 NUMBER(10)          NOT NULL,
    motivo                   VARCHAR2(300 CHAR)  NOT NULL,
    fecha_utc                TIMESTAMP           DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_movimiento_ecopuntos PRIMARY KEY (id_movimiento)
);

-- ------------------------------------------------------------------
-- MÓDULO AUDITORÍA (la llenan los disparadores, nunca la aplicación)
-- ------------------------------------------------------------------
-- 18. AUDITORIA_DEPOSITO: antes y después de cada verificación o corrección.
CREATE TABLE auditoria_deposito (
    id_auditoria                     NUMBER(10)          GENERATED ALWAYS AS IDENTITY,
    id_deposito                      NUMBER(10)          NOT NULL,
    operacion                        VARCHAR2(12 CHAR)   NOT NULL,
    estado_anterior                  NUMBER(1)           NOT NULL,
    estado_nuevo                     NUMBER(1)           NOT NULL,
    id_material_verificado_anterior  NUMBER(10),
    id_material_verificado_nuevo     NUMBER(10),
    cantidad_anterior                NUMBER(4),
    cantidad_nueva                   NUMBER(4),
    peso_medido_anterior_kg          NUMBER(9,4),
    peso_medido_nuevo_kg             NUMBER(9,4),
    id_verificador_anterior          NUMBER(10),
    id_verificador_nuevo             NUMBER(10),
    id_actor                         NUMBER(10),
    usuario_bd                       VARCHAR2(128 CHAR)  NOT NULL,
    motivo                           VARCHAR2(300 CHAR),
    fecha_utc                        TIMESTAMP           DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_auditoria_deposito PRIMARY KEY (id_auditoria)
);

-- 19. HISTORIAL_ESTADO_CONTENEDOR: cada cambio de disponibilidad de una caneca.
CREATE TABLE historial_estado_contenedor (
    id_historial     NUMBER(10)          GENERATED ALWAYS AS IDENTITY,
    id_contenedor    NUMBER(10)          NOT NULL,
    estado_anterior  NUMBER(1)           NOT NULL,
    estado_nuevo     NUMBER(1)           NOT NULL,
    id_actor         NUMBER(10),
    usuario_bd       VARCHAR2(128 CHAR)  NOT NULL,
    motivo           VARCHAR2(300 CHAR),
    fecha_utc        TIMESTAMP           DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_historial_estado_contenedor PRIMARY KEY (id_historial)
);

BEGIN
    DBMS_OUTPUT.PUT_LINE('02_tablas: 19 tablas creadas. Sigue con 03_restricciones.sql.');
END;
/
WHENEVER SQLERROR CONTINUE
