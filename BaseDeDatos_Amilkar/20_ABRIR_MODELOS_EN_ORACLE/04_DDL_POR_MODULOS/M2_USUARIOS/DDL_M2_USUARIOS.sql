	 CONSTRAINT "CK_ROL_CODIGO" CHECK (codigo IN (1, 2, 3)) ENABLE,
	 CONSTRAINT "CK_ROL_DESCRIPCION" CHECK (TRIM(descripcion) IS NOT NULL AND descripcion = TRIM(descripcion)) ENABLE
   ) ;

-- ---- Tabla del módulo: USUARIO ----
  CREATE TABLE "USUARIO"
   (	"ID_USUARIO" NUMBER(10,0) GENERATED ALWAYS AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"NOMBRE" VARCHAR2(100 CHAR) NOT NULL ENABLE,
	"CORREO_ELECTRONICO" VARCHAR2(254 CHAR) NOT NULL ENABLE,
	"FECHA_REGISTRO_UTC" TIMESTAMP (6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL ENABLE,
	"ACTIVO" NUMBER(1,0) DEFAULT 1 NOT NULL ENABLE,
	"VERSION_CONSENTIMIENTO" VARCHAR2(20 CHAR),
	"FECHA_CONSENTIMIENTO_UTC" TIMESTAMP (6),
	"ES_SINTETICO" NUMBER(1,0) DEFAULT 0 NOT NULL ENABLE,
	 CONSTRAINT "PK_USUARIO" PRIMARY KEY ("ID_USUARIO")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_USUARIO_CORREO" UNIQUE ("CORREO_ELECTRONICO")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_USUARIO_NOMBRE" CHECK (TRIM(nombre) IS NOT NULL AND nombre = TRIM(nombre) AND LENGTH(nombre) >= 2) ENABLE,
	 CONSTRAINT "CK_USUARIO_CORREO_MIN" CHECK (correo_electronico = LOWER(correo_electronico)) ENABLE,
	 CONSTRAINT "CK_USUARIO_CORREO_FORMA" CHECK (INSTR(correo_electronico, '@') > 1
                                                AND INSTR(correo_electronico, '.', INSTR(correo_electronico, '@')) > INSTR(correo_electronico, '@') + 1
                                                AND INSTR(correo_electronico, ' ') = 0) ENABLE,
	 CONSTRAINT "CK_USUARIO_ACTIVO" CHECK (activo IN (0, 1)) ENABLE,
	 CONSTRAINT "CK_USUARIO_CONSENTIMIENTO" CHECK (
        (version_consentimiento IS NULL AND fecha_consentimiento_utc IS NULL) OR
        (version_consentimiento IS NOT NULL AND fecha_consentimiento_utc IS NOT NULL)) ENABLE,
	 CONSTRAINT "CK_USUARIO_SINTETICO" CHECK (es_sintetico IN (0, 1)) ENABLE
   ) ;

-- ---- Tabla del módulo: USUARIO_ROL ----
  CREATE TABLE "USUARIO_ROL"
   (	"ID_USUARIO" NUMBER(10,0) NOT NULL ENABLE,
	"ID_ROL" NUMBER(10,0) NOT NULL ENABLE,
	"FECHA_ASIGNACION_UTC" TIMESTAMP (6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL ENABLE,
	 CONSTRAINT "PK_USUARIO_ROL" PRIMARY KEY ("ID_USUARIO", "ID_ROL")
  USING INDEX  ENABLE,
	 CONSTRAINT "FK_USUARIO_ROL_USUARIO" FOREIGN KEY ("ID_USUARIO")
	  REFERENCES "USUARIO" ("ID_USUARIO") ENABLE,
	 CONSTRAINT "FK_USUARIO_ROL_ROL" FOREIGN KEY ("ID_ROL")
	  REFERENCES "ROL" ("ID_ROL") ENABLE
   ) ;

-- ---- Tabla del módulo: CREDENCIAL_ACCESO ----
  CREATE TABLE "CREDENCIAL_ACCESO"
   (	"ID_USUARIO" NUMBER(10,0) NOT NULL ENABLE,
	"HASH_CONTRASENA" RAW(32) NOT NULL ENABLE,
	"SAL" RAW(16) NOT NULL ENABLE,
	"ITERACIONES" NUMBER(7,0) NOT NULL ENABLE,
	"INTENTOS_FALLIDOS" NUMBER(3,0) DEFAULT 0 NOT NULL ENABLE,
	"BLOQUEADA_HASTA_UTC" TIMESTAMP (6),
	"FECHA_CAMBIO_UTC" TIMESTAMP (6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL ENABLE,
	 CONSTRAINT "PK_CREDENCIAL_ACCESO" PRIMARY KEY ("ID_USUARIO")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_CREDENCIAL_HASH" CHECK (LENGTH(RAWTOHEX(hash_contrasena)) = 64) ENABLE,
	 CONSTRAINT "CK_CREDENCIAL_SAL" CHECK (LENGTH(RAWTOHEX(sal)) = 32) ENABLE,
	 CONSTRAINT "CK_CREDENCIAL_ITER" CHECK (iteraciones >= 100000) ENABLE,
	 CONSTRAINT "CK_CREDENCIAL_INTENTOS" CHECK (intentos_fallidos BETWEEN 0 AND 100) ENABLE,
	 CONSTRAINT "FK_CREDENCIAL_USUARIO" FOREIGN KEY ("ID_USUARIO")
	  REFERENCES "USUARIO" ("ID_USUARIO") ENABLE
   ) ;

-- ---- Tabla del módulo: VINCULO_TELEGRAM ----
  CREATE TABLE "VINCULO_TELEGRAM"
   (	"ID_VINCULO" NUMBER(10,0) GENERATED ALWAYS AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"ID_USUARIO" NUMBER(10,0) NOT NULL ENABLE,
	"TELEGRAM_USER_ID" NUMBER(19,0) NOT NULL ENABLE,
	"FECHA_VINCULO_UTC" TIMESTAMP (6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL ENABLE,
	"FECHA_BAJA_UTC" TIMESTAMP (6),
	 CONSTRAINT "PK_VINCULO_TELEGRAM" PRIMARY KEY ("ID_VINCULO")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_VINCULO_TELEGRAM_ID" CHECK (telegram_user_id > 0) ENABLE,
	 CONSTRAINT "CK_VINCULO_BAJA" CHECK (fecha_baja_utc IS NULL OR fecha_baja_utc >= fecha_vinculo_utc) ENABLE,
	 CONSTRAINT "FK_VINCULO_USUARIO" FOREIGN KEY ("ID_USUARIO")
	  REFERENCES "USUARIO" ("ID_USUARIO") ENABLE
   ) ;

-- ---- Índices de las tablas del módulo ----
  CREATE INDEX "IX_USUARIO_ROL_ROL" ON "USUARIO_ROL" ("ID_ROL")
  ;

  CREATE INDEX "IX_VINCULO_USUARIO" ON "VINCULO_TELEGRAM" ("ID_USUARIO")
  ;

  CREATE UNIQUE INDEX "UQ_VINCULO_TELEGRAM_ACTIVO" ON "VINCULO_TELEGRAM" (CASE  WHEN "FECHA_BAJA_UTC" IS NULL THEN "TELEGRAM_USER_ID" END )
  ;

  CREATE UNIQUE INDEX "UQ_VINCULO_USUARIO_ACTIVO" ON "VINCULO_TELEGRAM" (CASE  WHEN "FECHA_BAJA_UTC" IS NULL THEN "ID_USUARIO" END )
  ;

