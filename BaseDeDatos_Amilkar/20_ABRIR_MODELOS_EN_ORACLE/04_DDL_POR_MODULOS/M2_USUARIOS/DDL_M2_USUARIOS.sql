-- ---- Tabla del módulo: ROL ----
  CREATE TABLE "ROL"
   (	"ID_ROL" NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 4 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"CODIGO" NUMBER(2,0) NOT NULL ENABLE,
	"DESCRIPCION" VARCHAR2(200 CHAR) NOT NULL ENABLE,
	 CONSTRAINT "PK_ROL" PRIMARY KEY ("ID_ROL")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_ROL_CODIGO" UNIQUE ("CODIGO")
