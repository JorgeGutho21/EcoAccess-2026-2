	"SIN_SENSOR" NUMBER(1,0) DEFAULT 0 NOT NULL ENABLE,
	"ID_MATERIAL_DECLARADO" NUMBER(10,0) NOT NULL ENABLE,
	"CANTIDAD_DECLARADA" NUMBER(4,0),
	"PESO_ESTIMADO_KG" NUMBER(9,4),
	"ID_PESO_REFERENCIAL" NUMBER(10,0),
	"ESTADO_VERIFICACION" NUMBER(1,0) DEFAULT 0 NOT NULL ENABLE,
	"ID_MATERIAL_VERIFICADO" NUMBER(10,0),
	"CANTIDAD_VERIFICADA" NUMBER(4,0),
	"ID_VERIFICADOR" NUMBER(10,0),
	"FECHA_VERIFICACION_UTC" TIMESTAMP (6),
	"MOTIVO_VERIFICACION" VARCHAR2(300 CHAR),
	"PESO_MEDIDO_KG" NUMBER(9,4),
	"INSTRUMENTO_MEDICION" VARCHAR2(60 CHAR),
	"PRECISION_MEDICION_G" NUMBER(6,1),
	"FECHA_DETECCION_UTC" TIMESTAMP (6) NOT NULL ENABLE,
	 CONSTRAINT "PK_DEPOSITO" PRIMARY KEY ("ID_DEPOSITO")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_DEPOSITO_ORDEN" UNIQUE ("ID_ORDEN")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_DEPOSITO_EVENTO" UNIQUE ("ID_EVENTO")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_DEPOSITO_SIN_SENSOR" CHECK (sin_sensor IN (0, 1)) ENABLE,
	 CONSTRAINT "CK_DEPOSITO_CANT_DECL" CHECK (cantidad_declarada IS NULL OR cantidad_declarada BETWEEN 1 AND 1000) ENABLE,
	 CONSTRAINT "CK_DEPOSITO_ESTIMADO" CHECK (peso_estimado_kg IS NULL OR (peso_estimado_kg > 0 AND id_peso_referencial IS NOT NULL)) ENABLE,
	 CONSTRAINT "CK_DEPOSITO_ESTADO" CHECK (estado_verificacion IN (0, 1, 2)) ENABLE,
	 CONSTRAINT "CK_DEPOSITO_VERIFICACION" CHECK (
        (estado_verificacion = 0 AND id_material_verificado IS NULL AND cantidad_verificada IS NULL
             AND id_verificador IS NULL AND fecha_verificacion_utc IS NULL AND peso_medido_kg IS NULL)
     OR (estado_verificacion = 1 AND id_material_verificado IS NOT NULL AND id_verificador IS NOT NULL
             AND fecha_verificacion_utc IS NOT NULL AND fecha_verificacion_utc >= fecha_deteccion_utc)
     OR (estado_verificacion = 2 AND id_material_verificado IS NULL AND cantidad_verificada IS NULL
             AND peso_medido_kg IS NULL AND id_verificador IS NOT NULL AND motivo_verificacion IS NOT NULL
             AND fecha_verificacion_utc IS NOT NULL AND fecha_verificacion_utc >= fecha_deteccion_utc)) ENABLE,
	 CONSTRAINT "CK_DEPOSITO_CANT_VERIF" CHECK (cantidad_verificada IS NULL OR cantidad_verificada BETWEEN 1 AND 1000) ENABLE,
	 CONSTRAINT "CK_DEPOSITO_MOTIVO" CHECK (motivo_verificacion IS NULL
                                             OR (TRIM(motivo_verificacion) IS NOT NULL AND motivo_verificacion = TRIM(motivo_verificacion))) ENABLE,
	 CONSTRAINT "CK_DEPOSITO_MEDIDO" CHECK (
    (peso_medido_kg IS NULL AND instrumento_medicion IS NULL AND precision_medicion_g IS NULL) OR
    (peso_medido_kg IS NOT NULL AND instrumento_medicion IS NOT NULL AND precision_medicion_g IS NOT NULL
         AND peso_medido_kg > 0 AND TRIM(instrumento_medicion) IS NOT NULL AND precision_medicion_g > 0)) ENABLE
   ) ;

