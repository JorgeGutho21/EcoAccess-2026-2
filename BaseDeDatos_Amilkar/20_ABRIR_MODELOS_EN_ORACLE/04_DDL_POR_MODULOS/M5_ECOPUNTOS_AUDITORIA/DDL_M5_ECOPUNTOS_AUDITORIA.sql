-- ---- Tabla de CONTEXTO (otro módulo): DEPOSITO ----
  CREATE TABLE "DEPOSITO"
   (	"ID_DEPOSITO" NUMBER(10,0) GENERATED ALWAYS AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
