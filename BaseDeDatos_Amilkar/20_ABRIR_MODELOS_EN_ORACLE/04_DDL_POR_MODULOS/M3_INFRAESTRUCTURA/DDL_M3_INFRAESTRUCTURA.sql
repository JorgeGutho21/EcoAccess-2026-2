-- ---- Tabla del módulo: PUNTO_INSTALACION ----
  CREATE TABLE "PUNTO_INSTALACION"
   (	"ID_PUNTO_INSTALACION" NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 3 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"NOMBRE" VARCHAR2(100 CHAR) NOT NULL ENABLE,
	"REFERENCIA_UBICACION" VARCHAR2(200 CHAR),
	"CODIGO_QR_ESTACION" VARCHAR2(64 CHAR),
	"ACTIVO" NUMBER(1,0) DEFAULT 1 NOT NULL ENABLE,
	"ES_SINTETICO" NUMBER(1,0) DEFAULT 0 NOT NULL ENABLE,
	 CONSTRAINT "PK_PUNTO_INSTALACION" PRIMARY KEY ("ID_PUNTO_INSTALACION")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_PUNTO_NOMBRE" UNIQUE ("NOMBRE")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_PUNTO_QR_ESTACION" UNIQUE ("CODIGO_QR_ESTACION")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_PUNTO_NOMBRE" CHECK (TRIM(nombre) IS NOT NULL AND nombre = TRIM(nombre) AND LENGTH(nombre) >= 2) ENABLE,
	 CONSTRAINT "CK_PUNTO_QR_ESTACION" CHECK (codigo_qr_estacion IS NULL OR (LENGTH(codigo_qr_estacion) >= 16
        AND TRANSLATE(codigo_qr_estacion, '#ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_-', '#') IS NULL)) ENABLE,
	 CONSTRAINT "CK_PUNTO_ACTIVO" CHECK (activo IN (0, 1)) ENABLE,
	 CONSTRAINT "CK_PUNTO_SINTETICO" CHECK (es_sintetico IN (0, 1)) ENABLE
   ) ;

-- ---- Tabla de CONTEXTO (otro módulo): MATERIAL ----
  CREATE TABLE "MATERIAL"
   (	"ID_MATERIAL" NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 404 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"CODIGO" VARCHAR2(30 CHAR) NOT NULL ENABLE,
	"NOMBRE" VARCHAR2(100 CHAR) NOT NULL ENABLE,
	"CATEGORIA" NUMBER(1,0) NOT NULL ENABLE,
	"DESCRIPCION" VARCHAR2(500 CHAR),
	"HABILITADO" NUMBER(1,0) DEFAULT 1 NOT NULL ENABLE,
	 CONSTRAINT "PK_MATERIAL" PRIMARY KEY ("ID_MATERIAL")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_MATERIAL_CODIGO" UNIQUE ("CODIGO")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_MATERIAL_CATEGORIA" UNIQUE ("ID_MATERIAL", "CATEGORIA")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_MATERIAL_CODIGO" CHECK (LENGTH(codigo) >= 2
        AND INSTR('ABCDEFGHIJKLMNOPQRSTUVWXYZ', SUBSTR(codigo, 1, 1)) > 0
        AND TRANSLATE(codigo, '#ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_', '#') IS NULL) ENABLE,
	 CONSTRAINT "CK_MATERIAL_NOMBRE" CHECK (TRIM(nombre) IS NOT NULL AND nombre = TRIM(nombre) AND LENGTH(nombre) >= 2) ENABLE,
	 CONSTRAINT "CK_MATERIAL_CATEGORIA" CHECK (categoria IN (1, 2, 3, 4)) ENABLE,
	 CONSTRAINT "CK_MATERIAL_HABILITADO" CHECK (habilitado IN (0, 1)) ENABLE
   ) ;

-- ---- Tabla del módulo: CONTENEDOR ----
  CREATE TABLE "CONTENEDOR"
   (	"ID_CONTENEDOR" NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 22 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"ID_PUNTO_INSTALACION" NUMBER(10,0) NOT NULL ENABLE,
	"NOMBRE" VARCHAR2(100 CHAR) NOT NULL ENABLE,
	"CATEGORIA" NUMBER(1,0) NOT NULL ENABLE,
	"IDENTIFICADOR_QR" VARCHAR2(64 CHAR),
	"IDENTIFICADOR_DISPOSITIVO" VARCHAR2(40 CHAR),
	"FECHA_ALTA_UTC" TIMESTAMP (6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL ENABLE,
	"ESTADO" NUMBER(1,0) DEFAULT 2 NOT NULL ENABLE,
	 CONSTRAINT "PK_CONTENEDOR" PRIMARY KEY ("ID_CONTENEDOR")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_CONTENEDOR_QR" UNIQUE ("IDENTIFICADOR_QR")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_CONTENEDOR_DISPOSITIVO" UNIQUE ("IDENTIFICADOR_DISPOSITIVO")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_CONTENEDOR_PUNTO" UNIQUE ("ID_CONTENEDOR", "ID_PUNTO_INSTALACION")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_CONTENEDOR_CATEGORIA" UNIQUE ("ID_CONTENEDOR", "CATEGORIA")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_CONTENEDOR_NOMBRE" CHECK (TRIM(nombre) IS NOT NULL AND nombre = TRIM(nombre) AND LENGTH(nombre) >= 2) ENABLE,
	 CONSTRAINT "CK_CONTENEDOR_CATEGORIA" CHECK (categoria IN (1, 2, 3)) ENABLE,
	 CONSTRAINT "CK_CONTENEDOR_QR" CHECK (identificador_qr IS NULL OR (LENGTH(identificador_qr) >= 16
        AND TRANSLATE(identificador_qr, '#ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_-', '#') IS NULL)) ENABLE,
	 CONSTRAINT "CK_CONTENEDOR_DISPOSITIVO" CHECK (identificador_dispositivo IS NULL OR (LENGTH(identificador_dispositivo) BETWEEN 3 AND 40
        AND TRANSLATE(identificador_dispositivo, '#ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_-', '#') IS NULL)) ENABLE,
	 CONSTRAINT "CK_CONTENEDOR_ESTADO" CHECK (estado IN (1, 2, 3)) ENABLE,
	 CONSTRAINT "FK_CONTENEDOR_PUNTO" FOREIGN KEY ("ID_PUNTO_INSTALACION")
	  REFERENCES "PUNTO_INSTALACION" ("ID_PUNTO_INSTALACION") ENABLE
   ) ;

-- ---- Tabla del módulo: CONTENEDOR_MATERIAL ----
  CREATE TABLE "CONTENEDOR_MATERIAL"
   (	"ID_CONTENEDOR" NUMBER(10,0) NOT NULL ENABLE,
	"ID_MATERIAL" NUMBER(10,0) NOT NULL ENABLE,
	"CATEGORIA" NUMBER(1,0) NOT NULL ENABLE,
	 CONSTRAINT "PK_CONTENEDOR_MATERIAL" PRIMARY KEY ("ID_CONTENEDOR", "ID_MATERIAL")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_CONT_MAT_CATEGORIA" CHECK (categoria IN (1, 2, 3)) ENABLE,
	 CONSTRAINT "FK_CONT_MAT_CONTENEDOR" FOREIGN KEY ("ID_CONTENEDOR", "CATEGORIA")
	  REFERENCES "CONTENEDOR" ("ID_CONTENEDOR", "CATEGORIA") ENABLE,
	 CONSTRAINT "FK_CONT_MAT_MATERIAL" FOREIGN KEY ("ID_MATERIAL", "CATEGORIA")
	  REFERENCES "MATERIAL" ("ID_MATERIAL", "CATEGORIA") ENABLE
   ) ;

-- ---- Índices de las tablas del módulo ----
  CREATE INDEX "IX_CONTENEDOR_PUNTO" ON "CONTENEDOR" ("ID_PUNTO_INSTALACION")
  ;

  CREATE UNIQUE INDEX "UQ_CONTENEDOR_COLOR_ACTIVO" ON "CONTENEDOR" (CASE  WHEN "ESTADO"<>3 THEN "ID_PUNTO_INSTALACION" END , CASE  WHEN "ESTADO"<>3 THEN "CATEGORIA" END )
  ;

  CREATE INDEX "IX_CONT_MAT_CONTENEDOR_CAT" ON "CONTENEDOR_MATERIAL" ("ID_CONTENEDOR", "CATEGORIA")
  ;

  CREATE INDEX "IX_CONT_MAT_MATERIAL" ON "CONTENEDOR_MATERIAL" ("ID_MATERIAL", "CATEGORIA")
  ;

