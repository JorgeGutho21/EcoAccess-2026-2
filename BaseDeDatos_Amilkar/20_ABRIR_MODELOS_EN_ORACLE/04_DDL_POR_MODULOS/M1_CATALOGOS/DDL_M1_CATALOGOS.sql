-- ---- Tabla del módulo: MATERIAL ----
  CREATE TABLE "MATERIAL"
   (	"ID_MATERIAL" NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 404 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"CODIGO" VARCHAR2(30 CHAR) NOT NULL ENABLE,
	"NOMBRE" VARCHAR2(100 CHAR) NOT NULL ENABLE,
	"CATEGORIA" NUMBER(1,0) NOT NULL ENABLE,
	"DESCRIPCION" VARCHAR2(500 CHAR),
	"HABILITADO" NUMBER(1,0) DEFAULT 1 NOT NULL ENABLE,
	 CONSTRAINT "PK_MATERIAL" PRIMARY KEY ("ID_MATERIAL")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_MATERIAL_CODIGO" UNIQUE ("CODIGO")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_MATERIAL_CATEGORIA" UNIQUE ("ID_MATERIAL", "CATEGORIA")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_MATERIAL_CODIGO" CHECK (LENGTH(codigo) >= 2
        AND INSTR('ABCDEFGHIJKLMNOPQRSTUVWXYZ', SUBSTR(codigo, 1, 1)) > 0
        AND TRANSLATE(codigo, '#ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_', '#') IS NULL) ENABLE,
	 CONSTRAINT "CK_MATERIAL_NOMBRE" CHECK (TRIM(nombre) IS NOT NULL AND nombre = TRIM(nombre) AND LENGTH(nombre) >= 2) ENABLE,
	 CONSTRAINT "CK_MATERIAL_CATEGORIA" CHECK (categoria IN (1, 2, 3, 4)) ENABLE,
	 CONSTRAINT "CK_MATERIAL_HABILITADO" CHECK (habilitado IN (0, 1)) ENABLE
   ) ;

-- ---- Tabla del módulo: PESO_REFERENCIAL ----
  CREATE TABLE "PESO_REFERENCIAL"
   (	"ID_PESO_REFERENCIAL" NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 23 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"ID_MATERIAL" NUMBER(10,0) NOT NULL ENABLE,
	"CLAVE_OBJETO" VARCHAR2(40 CHAR) NOT NULL ENABLE,
	"DESCRIPCION_OBJETO" VARCHAR2(150 CHAR) NOT NULL ENABLE,
	"ESTADO_VISUAL" NUMBER(1,0) DEFAULT 0 NOT NULL ENABLE,
	"GRAMOS_MINIMO" NUMBER(8,1) NOT NULL ENABLE,
	"GRAMOS_TIPICO" NUMBER(8,1) NOT NULL ENABLE,
	"GRAMOS_MAXIMO" NUMBER(8,1) NOT NULL ENABLE,
	"FUENTE" VARCHAR2(200 CHAR) NOT NULL ENABLE,
	 CONSTRAINT "PK_PESO_REFERENCIAL" PRIMARY KEY ("ID_PESO_REFERENCIAL")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_PESO_OBJETO_ESTADO" UNIQUE ("CLAVE_OBJETO", "ESTADO_VISUAL")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_PESO_CLAVE" CHECK (LENGTH(clave_objeto) >= 2
        AND TRANSLATE(clave_objeto, '#ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_', '#') IS NULL) ENABLE,
	 CONSTRAINT "CK_PESO_DESCRIPCION" CHECK (TRIM(descripcion_objeto) IS NOT NULL AND descripcion_objeto = TRIM(descripcion_objeto)) ENABLE,
	 CONSTRAINT "CK_PESO_ESTADO_VISUAL" CHECK (estado_visual IN (0, 1, 2, 3)) ENABLE,
	 CONSTRAINT "CK_PESO_ORDEN" CHECK (gramos_minimo > 0 AND gramos_minimo <= gramos_tipico AND gramos_tipico <= gramos_maximo) ENABLE,
	 CONSTRAINT "CK_PESO_FUENTE" CHECK (TRIM(fuente) IS NOT NULL AND fuente = TRIM(fuente)) ENABLE,
	 CONSTRAINT "FK_PESO_MATERIAL" FOREIGN KEY ("ID_MATERIAL")
	  REFERENCES "MATERIAL" ("ID_MATERIAL") ENABLE
   ) ;

