-- ---- Tabla de CONTEXTO (otro módulo): INTERACCION ----
  CREATE TABLE "INTERACCION"
   (	"ID_INTERACCION" NUMBER(10,0) GENERATED ALWAYS AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"ID_PUNTO_INSTALACION" NUMBER(10,0) NOT NULL ENABLE,
	"ID_CONTENEDOR" NUMBER(10,0),
	"ID_USUARIO" NUMBER(10,0),
	"CANAL" NUMBER(1,0) NOT NULL ENABLE,
	"ESTADO" NUMBER(1,0) DEFAULT 1 NOT NULL ENABLE,
	"ID_MATERIAL_SUGERIDO" NUMBER(10,0),
	"CONFIANZA_SUGERIDA" NUMBER(4,3),
	"ID_MATERIAL_CONFIRMADO" NUMBER(10,0),
	"CANTIDAD_DECLARADA" NUMBER(4,0),
	"ID_OPERARIO" NUMBER(10,0),
	"MOTIVO" VARCHAR2(300 CHAR),
	"FECHA_INICIO_UTC" TIMESTAMP (6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL ENABLE,
	"FECHA_CIERRE_UTC" TIMESTAMP (6),
	"ES_SINTETICO" NUMBER(1,0) DEFAULT 0 NOT NULL ENABLE,
	 CONSTRAINT "PK_INTERACCION" PRIMARY KEY ("ID_INTERACCION")
  USING INDEX  ENABLE,
	 CONSTRAINT "UQ_INTERACCION_CONTENEDOR" UNIQUE ("ID_INTERACCION", "ID_CONTENEDOR")
  USING INDEX  ENABLE,
	 CONSTRAINT "CK_INTERACCION_CANAL" CHECK (canal IN (1, 2, 3, 4, 5)) ENABLE,
	 CONSTRAINT "CK_INTERACCION_ESTADO" CHECK (estado IN (1, 2, 3, 4, 5)) ENABLE,
	 CONSTRAINT "CK_INTERACCION_CONFIANZA" CHECK (confianza_sugerida BETWEEN 0 AND 1) ENABLE,
	 CONSTRAINT "CK_INTERACCION_SUGERENCIA" CHECK ((id_material_sugerido IS NULL AND confianza_sugerida IS NULL)
                                               OR (id_material_sugerido IS NOT NULL AND confianza_sugerida IS NOT NULL)) ENABLE,
	 CONSTRAINT "CK_INTERACCION_CANTIDAD" CHECK (cantidad_declarada IS NULL OR cantidad_declarada BETWEEN 1 AND 1000) ENABLE,
	 CONSTRAINT "CK_INTERACCION_MOTIVO" CHECK (motivo IS NULL OR (TRIM(motivo) IS NOT NULL AND motivo = TRIM(motivo))) ENABLE,
	 CONSTRAINT "CK_INTERACCION_CIERRE" CHECK (
        (estado IN (1, 2) AND fecha_cierre_utc IS NULL) OR
        (estado IN (3, 4, 5) AND fecha_cierre_utc IS NOT NULL AND fecha_cierre_utc >= fecha_inicio_utc)) ENABLE,
	 CONSTRAINT "CK_INTERACCION_AUTORIZADA" CHECK (estado NOT IN (2, 3)
                                               OR (id_material_confirmado IS NOT NULL AND id_contenedor IS NOT NULL)) ENABLE,
	 CONSTRAINT "CK_INTERACCION_RECHAZO" CHECK (estado <> 5 OR motivo IS NOT NULL) ENABLE,
	 CONSTRAINT "CK_INTERACCION_MANUAL" CHECK (
        (canal = 2 AND id_operario IS NOT NULL AND motivo IS NOT NULL AND id_material_sugerido IS NULL) OR
        (canal <> 2 AND id_operario IS NULL)) ENABLE,
	 CONSTRAINT "CK_INTERACCION_SINTETICO" CHECK (es_sintetico IN (0, 1)) ENABLE,
	 CONSTRAINT "FK_INTERACCION_MAT_SUG" FOREIGN KEY ("ID_MATERIAL_SUGERIDO")
	  REFERENCES "MATERIAL" ("ID_MATERIAL") ENABLE,
	 CONSTRAINT "FK_INTERACCION_MAT_CONF" FOREIGN KEY ("ID_MATERIAL_CONFIRMADO")
	  REFERENCES "MATERIAL" ("ID_MATERIAL") ENABLE
   ) ;

