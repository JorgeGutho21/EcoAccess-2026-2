-- 10. Vistas académicas sobre las tablas reales (mismos nombres y columnas que ECOACCESS_BD, para Power BI).
CREATE OR REPLACE VIEW vw_caneca_estacion AS
SELECT p.id_punto_instalacion, p.nombre AS estacion, c.identificador_qr AS codigo_qr_estacion,
       c.id_contenedor, c.nombre AS caneca, k.categoria,
       DECODE(k.categoria, 1, 'BLANCA', 2, 'VERDE', 3, 'NEGRA') AS color,
       DECODE(k.categoria, 1, 'Aprovechables', 2, 'Orgánicos aprovechables', 3, 'No aprovechables') AS tipo_residuo,
       c.estado, DECODE(c.estado, 1, 'EN SERVICIO', 2, 'FUERA DE SERVICIO', 3, 'DADA DE BAJA') AS estado_texto,
       c.identificador_qr AS qr_legado_caneca, k.identificador_dispositivo,
       CASE WHEN UPPER(c.nombre) LIKE '%FICTIC%' OR UPPER(p.nombre) LIKE '%SIMULACI%' THEN 1 ELSE 0 END AS es_sintetico
FROM   contenedor c
JOIN   punto_instalacion p ON p.id_punto_instalacion = c.id_punto_instalacion
LEFT JOIN configuracion_caneca k ON k.id_contenedor = c.id_contenedor
WITH READ ONLY;

CREATE OR REPLACE VIEW vw_deposito_detalle AS
SELECT d.id_deposito, i.id_interaccion, i.id_usuario AS id_titular, u.nombre AS titular,
       c.id_contenedor, c.nombre AS caneca, DECODE(k.categoria, 1, 'BLANCA', 2, 'VERDE', 3, 'NEGRA') AS color,
       p.nombre AS estacion, md.codigo AS material_declarado, mv.codigo AS material_verificado,
       i.cantidad_declarada, d.cantidad_verificada,
       DECODE(d.sin_sensor, 1, 'DECLARADO SIN SENSOR', 'DETECTADO POR SENSOR') AS evidencia_fisica,
       pkg_deposito.estado(d.id_deposito) AS estado_verificacion,
       DECODE(pkg_deposito.estado(d.id_deposito), 0, 'PENDIENTE', 1, 'VERIFICADO', 2, 'RECHAZADO') AS estado_texto,
       d.id_verificador, uv.nombre AS verificador,
       d.peso_estimado_kg, ROUND(d.peso_estimado_kg * 1000, 1) AS peso_estimado_g,
       d.peso_medido_kg, ROUND(d.peso_medido_kg * 1000, 1) AS peso_medido_g,
       d.fecha_deteccion_utc,
       CAST(FROM_TZ(d.fecha_deteccion_utc, 'UTC') AT TIME ZONE 'America/Bogota' AS DATE) AS fecha_colombia,
       i.canal,
       CASE WHEN i.canal IN (3, 4) OR UPPER(c.nombre) LIKE '%FICTIC%' OR UPPER(p.nombre) LIKE '%SIMULACI%'
                 OR REGEXP_LIKE(md.codigo, '^(BR_|IT_|TEST_|PRUEBA_)') THEN 1 ELSE 0 END AS es_sintetico
FROM   deposito d
JOIN   orden_apertura o    ON o.id_orden = d.id_orden
JOIN   interaccion i       ON i.id_interaccion = o.id_interaccion
JOIN   contenedor c        ON c.id_contenedor = o.id_contenedor
JOIN   punto_instalacion p ON p.id_punto_instalacion = c.id_punto_instalacion
JOIN   material md         ON md.id_material = d.id_material_declarado
LEFT JOIN configuracion_caneca k ON k.id_contenedor = c.id_contenedor
LEFT JOIN material mv      ON mv.id_material = d.id_material_verificado
LEFT JOIN usuario u        ON u.id_usuario = i.id_usuario
LEFT JOIN usuario uv       ON uv.id_usuario = d.id_verificador
WITH READ ONLY;

CREATE OR REPLACE VIEW vw_saldo_ecopuntos AS
SELECT u.id_usuario, u.nombre,
       NVL(SUM(m.puntos), 0) AS saldo,
       NVL(SUM(CASE WHEN m.tipo = 1 THEN m.puntos END), 0) AS acreditados,
       NVL(SUM(CASE WHEN m.tipo = 2 THEN m.puntos END), 0) AS revertidos,
       COUNT(m.id_movimiento) AS movimientos,
       0 AS es_sintetico
FROM   usuario u
JOIN   usuario_rol ur ON ur.id_usuario = u.id_usuario
JOIN   rol r          ON r.id_rol = ur.id_rol AND r.codigo = 1
LEFT JOIN movimiento_ecopuntos m ON m.id_usuario = u.id_usuario
GROUP  BY u.id_usuario, u.nombre
WITH READ ONLY;

CREATE OR REPLACE VIEW vw_recorrido AS
SELECT i.id_interaccion, i.id_usuario, c.id_punto_instalacion, i.canal,
       DECODE(i.estado, 1, 'INICIADA', 2, 'AUTORIZADA', 3, 'CON DEPOSITO', 4, 'SIN DEPOSITO', 5, 'RECHAZADA') AS estado_sesion,
       i.id_material_sugerido, o.id_orden,
       DECODE(o.estado, 1,'EMITIDA',2,'ENVIADA',3,'ACUSADA',4,'ABIERTA',5,'DETECTADA',6,'CERRADA',7,'VENCIDA',8,'FALLIDA') AS estado_orden,
       (SELECT COUNT(*) FROM evento_dispositivo e WHERE e.id_orden = o.id_orden AND e.tipo = 2) AS aperturas_confirmadas,
       d.id_deposito, d.sin_sensor,
       CASE WHEN d.id_deposito IS NULL THEN NULL ELSE pkg_deposito.estado(d.id_deposito) END AS estado_verificacion,
       CAST(FROM_TZ(i.fecha_inicio_utc, 'UTC') AT TIME ZONE 'America/Bogota' AS DATE) AS inicio_colombia,
       CASE WHEN i.canal IN (3, 4) THEN 1 ELSE 0 END AS es_sintetico
FROM   interaccion i
