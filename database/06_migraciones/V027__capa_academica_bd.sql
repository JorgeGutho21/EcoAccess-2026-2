CREATE OR REPLACE TRIGGER trg_deposito_bloqueo_cerrado
BEFORE UPDATE ON deposito
FOR EACH ROW
WHEN (OLD.id_material_verificado IS NOT NULL)
BEGIN
    IF NOT pkg_deposito.correccion_en_curso THEN
        RAISE_APPLICATION_ERROR(-20103, 'El depósito ' || :OLD.id_deposito
            || ' ya está VERIFICADO. Solo se cambia con PKG_DEPOSITO.corregir_verificacion y un motivo.');
    END IF;
END;
/
CREATE OR REPLACE TRIGGER trg_deposito_coherencia
BEFORE INSERT OR UPDATE ON deposito
FOR EACH ROW
FOLLOWS trg_deposito_bloqueo_cerrado
DECLARE
    v_titular    interaccion.id_usuario%TYPE;
    v_contenedor contenedor.id_contenedor%TYPE;
    v_admitido   NUMBER;
BEGIN
    IF UPDATING THEN
        IF :NEW.id_orden <> :OLD.id_orden OR :NEW.id_evento <> :OLD.id_evento
           OR :NEW.id_material_declarado <> :OLD.id_material_declarado
           OR :NEW.sin_sensor <> :OLD.sin_sensor
           OR :NEW.fecha_deteccion_utc <> :OLD.fecha_deteccion_utc THEN
            RAISE_APPLICATION_ERROR(-20109, 'Orden, evento, material declarado, sensor y fecha de detección no se modifican.');
        END IF;
    END IF;
    BEGIN
        SELECT i.id_usuario, o.id_contenedor INTO v_titular, v_contenedor
        FROM   orden_apertura o JOIN interaccion i ON i.id_interaccion = o.id_interaccion
        WHERE  o.id_orden = :NEW.id_orden;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN;                                    -- orden inexistente: la rechaza la FK
    END;
    IF INSERTING THEN
        SELECT COUNT(*) INTO v_admitido FROM contenedor_material
        WHERE  id_contenedor = v_contenedor AND id_material = :NEW.id_material_declarado;
        IF v_admitido = 0 THEN
            RAISE_APPLICATION_ERROR(-20102, 'La caneca ' || v_contenedor || ' no admite el material declarado '
                || :NEW.id_material_declarado || '.');
        END IF;
    END IF;
    IF :NEW.id_verificador IS NOT NULL AND (INSERTING OR NVL(:OLD.id_verificador, -1) <> :NEW.id_verificador) THEN
        IF pkg_contexto_app.tiene_rol(:NEW.id_verificador, 2) = 0 AND pkg_contexto_app.tiene_rol(:NEW.id_verificador, 3) = 0 THEN
            RAISE_APPLICATION_ERROR(-20104, 'El verificador ' || :NEW.id_verificador || ' no es Operario ni Administrador activo.');
        END IF;
    END IF;
END;
/
CREATE OR REPLACE TRIGGER trg_deposito_aud_verificacion
AFTER UPDATE OF id_material_verificado, cantidad_verificada, peso_medido_kg, id_verificador ON deposito
FOR EACH ROW
DECLARE
    v_cambios NUMBER;
    v_ant     NUMBER := CASE WHEN :OLD.id_material_verificado IS NOT NULL THEN 1 ELSE 0 END;
    v_nue     NUMBER := CASE WHEN :NEW.id_material_verificado IS NOT NULL THEN 1 ELSE 0 END;
    FUNCTION cambio(a NUMBER, b NUMBER) RETURN NUMBER IS
    BEGIN
        RETURN CASE WHEN (a = b) OR (a IS NULL AND b IS NULL) THEN 0 ELSE 1 END;
    END;
BEGIN
    v_cambios := cambio(:OLD.id_material_verificado, :NEW.id_material_verificado) + cambio(:OLD.cantidad_verificada, :NEW.cantidad_verificada)
               + cambio(:OLD.peso_medido_kg, :NEW.peso_medido_kg) + cambio(:OLD.id_verificador, :NEW.id_verificador);
    IF v_cambios = 0 THEN
        RETURN;
    END IF;
    INSERT INTO auditoria_deposito (id_deposito, operacion, estado_anterior, estado_nuevo,
        id_material_verificado_anterior, id_material_verificado_nuevo, cantidad_anterior, cantidad_nueva,
        peso_medido_anterior_kg, peso_medido_nuevo_kg, id_verificador_anterior, id_verificador_nuevo, id_actor, usuario_bd, motivo)
    VALUES (:NEW.id_deposito,
        CASE WHEN v_ant = 0 AND v_nue = 1 THEN 'VERIFICACION' WHEN v_ant = 1 AND v_nue = 0 THEN 'REAPERTURA' ELSE 'CORRECCION' END,
        v_ant, v_nue, :OLD.id_material_verificado, :NEW.id_material_verificado, :OLD.cantidad_verificada, :NEW.cantidad_verificada,
        :OLD.peso_medido_kg, :NEW.peso_medido_kg, :OLD.id_verificador, :NEW.id_verificador,
        NVL(pkg_contexto_app.actor, :NEW.id_verificador), USER, pkg_contexto_app.motivo);
END;
