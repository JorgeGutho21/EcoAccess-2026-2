-- 12. Permisos: lectura de las vistas y tablas nuevas para los roles de consulta y edición que ya existan (V-admin).
DECLARE
    n NUMBER;
    PROCEDURE conceder(p_privilegio VARCHAR2, p_objeto VARCHAR2, p_rol VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE 'GRANT ' || p_privilegio || ' ON ' || p_objeto || ' TO ' || p_rol;
    EXCEPTION WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('V027: no se concedió ' || p_privilegio || ' ON ' || p_objeto || ' TO ' || p_rol || ' (' || SQLCODE || ').');
    END;
BEGIN
    FOR r IN (SELECT DISTINCT grantee FROM user_tab_privs_made WHERE grantee IN ('ECOACCESS_ROL_CONSULTA', 'ECOACCESS_ROL_EDICION')) LOOP
        FOR o IN (SELECT object_name FROM user_objects
                  WHERE object_name IN ('VW_CANECA_ESTACION', 'VW_DEPOSITO_DETALLE', 'VW_SALDO_ECOPUNTOS', 'VW_RECORRIDO', 'VW_BI_CIUDADANOS',
                                        'VW_BI_DEPOSITOS', 'VW_BI_CONSULTAS_VISION', 'VW_BI_ECOPUNTOS', 'VW_BI_AUDITORIA',
                                        'PESO_REFERENCIAL', 'HISTORIAL_ESTADO_CONTENEDOR', 'AUDITORIA_DEPOSITO')
                  AND object_type IN ('VIEW', 'TABLE')) LOOP
            conceder('SELECT', o.object_name, r.grantee);
        END LOOP;
    END LOOP;
    SELECT COUNT(*) INTO n FROM user_tab_privs_made WHERE grantee = 'ECOACCESS_ROL_EDICION' AND ROWNUM = 1;
    IF n = 1 THEN
        FOR o IN (SELECT 'PKG_DEPOSITO' x FROM dual UNION ALL SELECT 'PKG_ECOPUNTOS' FROM dual UNION ALL SELECT 'PKG_ESTADISTICAS' FROM dual
                  UNION ALL SELECT 'PKG_CONTEXTO_APP' FROM dual UNION ALL SELECT 'PR_CAMBIAR_ESTADO_CONTENEDOR' FROM dual
                  UNION ALL SELECT 'FN_PESO_ESTIMADO_KG' FROM dual UNION ALL SELECT 'FN_DEPOSITOS_CIUDADANO' FROM dual) LOOP
            conceder('EXECUTE', o.x, 'ECOACCESS_ROL_EDICION');
        END LOOP;
    END IF;
END;
