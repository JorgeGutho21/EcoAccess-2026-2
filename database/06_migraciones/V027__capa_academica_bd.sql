-- 4. PKG_CONTEXTO_APP: qué persona de la aplicación actúa (la cuenta de base de datos es compartida).
CREATE OR REPLACE PACKAGE pkg_contexto_app AS
    -- ECOACCESS_V027
    PROCEDURE fijar_actor(p_id_usuario IN usuario.id_usuario%TYPE, p_motivo IN VARCHAR2 DEFAULT NULL);
