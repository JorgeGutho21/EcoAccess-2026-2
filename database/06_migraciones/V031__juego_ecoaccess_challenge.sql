-- Clasificación: mayor puntaje, menor tiempo medido por el servidor, fin más temprano e identificador (desempate final).
CREATE OR REPLACE VIEW vw_juego_clasificacion AS
SELECT i.competencia_id,
       i.id AS intento_id,
       p.alias,
       i.puntaje,
       i.aciertos,
       i.errores,
       i.tiempo_ms,
       i.fin,
       i.posicion_final,
       ROW_NUMBER() OVER (PARTITION BY i.competencia_id ORDER BY i.puntaje DESC, i.tiempo_ms ASC, i.fin ASC, i.id ASC) AS posicion
  FROM eco_juego_intentos i
  JOIN eco_juego_participantes p ON p.id = i.participante_id
 WHERE i.estado = 'FINALIZADO'
