-- =====================================================================
-- EcoAccess P3 — tablas iniciales (versión 001)
-- Archivo: database/02_tablas/01_crear_tablas_iniciales.sql
--
-- Crea: ROL, USUARIO, USUARIO_ROL, MATERIAL, PUNTO_INSTALACION,
--       CONTENEDOR y CONTENEDOR_MATERIAL.
-- Diccionario de datos: database/01_modelo/DICCIONARIO_DATOS.md
--
-- Ejecutar conectado como ECOACCESS_P3 en FREEPDB1 (F5 en SQL Developer).
-- Compatible con Oracle 19c o superior: no usa IF NOT EXISTS ni BOOLEAN de 23ai.
--
-- Antes de crear nada revisa cuántas de las siete tablas existen:
--   * 0 -> crea todo.
--   * 7 -> ya estaba instalado; se detiene sin tocar nada (ORA-20010).
--   * 1 a 6 -> instalación parcial (por ejemplo, un fallo a mitad de la primera
--     ejecución); se detiene, lista las que existen e indica el script de
--     recuperación 00_recuperar_instalacion_parcial.sql (ORA-20011).
-- Los cambios posteriores a la versión 001 van en database/06_migraciones.
--
-- Convenciones:
--   * Textos en VARCHAR2(n CHAR): la longitud se cuenta en caracteres, no en
--     bytes, porque una letra con tilde ocupa dos bytes en AL32UTF8.
--   * Verdadero/falso en NUMBER(1) con CHECK (0, 1).
--   * Fechas de eventos en TIMESTAMP con hora UTC.
--   * Enumeraciones guardadas como número, con los mismos valores del enum C#.
--   * Sin ON DELETE CASCADE: el historial no se borra en cadena.
-- =====================================================================

SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

-- 0. Protección contra una segunda ejecución o una instalación a medias.
DECLARE
    v_existentes NUMBER;
    v_lista      VARCHAR2(400);
BEGIN
    SELECT COUNT(*), LISTAGG(table_name, ', ') WITHIN GROUP (ORDER BY table_name)
    INTO   v_existentes, v_lista
    FROM   user_tables
    WHERE  table_name IN ('ROL', 'USUARIO', 'USUARIO_ROL', 'MATERIAL',
                          'PUNTO_INSTALACION', 'CONTENEDOR', 'CONTENEDOR_MATERIAL');

    IF v_existentes = 7 THEN
        RAISE_APPLICATION_ERROR(-20010,
            'Las siete tablas iniciales de P3 ya existen. No se modificó nada; usa database/06_migraciones.');
    ELSIF v_existentes > 0 THEN
        RAISE_APPLICATION_ERROR(-20011,
            'Instalación parcial: existen ' || v_existentes || ' de 7 tablas (' || v_lista || '). '
            || 'No se modificó nada; revisa database/02_tablas/00_recuperar_instalacion_parcial.sql.');
    END IF;
END;
/

-- 1. ROL: catálogo de los tres roles aprobados.
CREATE TABLE rol (
    id_rol       NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    codigo       NUMBER(2)           NOT NULL,
    descripcion  VARCHAR2(200 CHAR)  NOT NULL,
    CONSTRAINT pk_rol            PRIMARY KEY (id_rol),
    CONSTRAINT uq_rol_codigo     UNIQUE (codigo),
    CONSTRAINT ck_rol_codigo     CHECK (codigo IN (1, 2, 3)),  -- CodigoRol: Ciudadano, Operario, Administrador
    CONSTRAINT ck_rol_descripcion CHECK (TRIM(descripcion) IS NOT NULL AND descripcion = TRIM(descripcion))
);

-- 2. USUARIO: identidad mínima y consentimiento vigente (RN-01). Sin contraseñas.
CREATE TABLE usuario (
    id_usuario                NUMBER(10)          GENERATED ALWAYS AS IDENTITY,
    nombre                    VARCHAR2(100 CHAR)  NOT NULL,
    correo_electronico        VARCHAR2(254 CHAR)  NOT NULL,
    fecha_registro_utc        TIMESTAMP           NOT NULL,
    activo                    NUMBER(1)           DEFAULT 1 NOT NULL,
    version_consentimiento    VARCHAR2(20 CHAR),
    fecha_consentimiento_utc  TIMESTAMP,
    CONSTRAINT pk_usuario               PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_correo        UNIQUE (correo_electronico),
    -- Nombres: TRIM de un texto solo de espacios es NULL y un CHECK con resultado desconocido
    -- se acepta; por eso se exige TRIM(...) IS NOT NULL. Además, sin espacios sobrantes,
    -- igual que la entidad, que siempre guarda el texto recortado.
    CONSTRAINT ck_usuario_nombre        CHECK (TRIM(nombre) IS NOT NULL AND nombre = TRIM(nombre) AND LENGTH(nombre) >= 2),
    -- La entidad guarda el correo en minúsculas; así la unicidad no depende de mayúsculas.
    CONSTRAINT ck_usuario_correo_min    CHECK (correo_electronico = LOWER(correo_electronico)),
    CONSTRAINT ck_usuario_activo        CHECK (activo IN (0, 1)),
    -- Versión y fecha del consentimiento van juntas o no van (misma regla que la entidad Usuario).
    CONSTRAINT ck_usuario_consentimiento CHECK (
        (version_consentimiento IS NULL AND fecha_consentimiento_utc IS NULL)
        OR (version_consentimiento IS NOT NULL AND fecha_consentimiento_utc IS NOT NULL))
);

-- 3. USUARIO_ROL: relación muchos a muchos; una cuenta puede tener varios roles.
--    «Al menos un rol por usuario» no se puede expresar con una restricción simple:
--    lo garantizan la entidad Usuario y la transacción del repositorio.
--    FECHA_ASIGNACION_UTC es metadato técnico que pone Oracle: la entidad no la lee ni la escribe.
--    El historial con valor de evidencia (quién asignó y cuándo) va en la auditoría.
CREATE TABLE usuario_rol (
    id_usuario            NUMBER(10)  NOT NULL,
    id_rol                NUMBER(10)  NOT NULL,
    fecha_asignacion_utc  TIMESTAMP   DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_usuario_rol          PRIMARY KEY (id_usuario, id_rol),
    CONSTRAINT fk_usuario_rol_usuario  FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_usuario_rol_rol      FOREIGN KEY (id_rol)     REFERENCES rol (id_rol)
);

-- Índice de la clave foránea a ROL: «¿quiénes son administradores?» y evita bloqueos al tocar ROL.
CREATE INDEX ix_usuario_rol_rol ON usuario_rol (id_rol);

-- 4. MATERIAL: catálogo validado contra el que se contrasta la sugerencia de la IA.
CREATE TABLE material (
    id_material   NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    codigo        VARCHAR2(30 CHAR)   NOT NULL,
    nombre        VARCHAR2(100 CHAR)  NOT NULL,
    categoria     NUMBER(1)           NOT NULL,
    descripcion   VARCHAR2(500 CHAR),
    habilitado    NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT pk_material             PRIMARY KEY (id_material),
    CONSTRAINT uq_material_codigo      UNIQUE (codigo),
    -- Misma regla que la entidad: empieza por letra y solo admite A-Z, 0-9 y guion bajo.
    -- Se comparan los caracteres uno por uno (INSTR y TRANSLATE) para no depender de la configuración
    -- de idioma: REGEXP_LIKE con [A-Z] y BETWEEN 'A' AND 'Z' usan el orden lingüístico si NLS_SORT
    -- no es BINARY y pueden aceptar letras con tilde.
    CONSTRAINT ck_material_codigo      CHECK (
        LENGTH(codigo) >= 2
        AND INSTR('ABCDEFGHIJKLMNOPQRSTUVWXYZ', SUBSTR(codigo, 1, 1)) > 0
        AND TRANSLATE(codigo, '#ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_', '#') IS NULL),
    CONSTRAINT ck_material_nombre      CHECK (TRIM(nombre) IS NOT NULL AND nombre = TRIM(nombre) AND LENGTH(nombre) >= 2),
    CONSTRAINT ck_material_categoria   CHECK (categoria IN (1, 2, 3, 4)),  -- CategoriaMaterial
    CONSTRAINT ck_material_habilitado  CHECK (habilitado IN (0, 1))
);

-- 5. PUNTO_INSTALACION: lugar físico de la caneca; el sector geográfico se agregará con una migración.
CREATE TABLE punto_instalacion (
    id_punto_instalacion  NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre                VARCHAR2(100 CHAR)  NOT NULL,
    referencia_ubicacion  VARCHAR2(200 CHAR),
    activo                NUMBER(1)           DEFAULT 1 NOT NULL,
    CONSTRAINT pk_punto_instalacion      PRIMARY KEY (id_punto_instalacion),
    CONSTRAINT uq_punto_instalacion_nom  UNIQUE (nombre),
    CONSTRAINT ck_punto_instalacion_nom  CHECK (TRIM(nombre) IS NOT NULL AND nombre = TRIM(nombre) AND LENGTH(nombre) >= 2),
    CONSTRAINT ck_punto_instalacion_act  CHECK (activo IN (0, 1))
);

-- 6. CONTENEDOR: la caneca y su QR público. Nace fuera de servicio (ESTADO = 2).
CREATE TABLE contenedor (
    id_contenedor         NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_punto_instalacion  NUMBER(10)          NOT NULL,
    nombre                VARCHAR2(100 CHAR)  NOT NULL,
    identificador_qr      VARCHAR2(64 CHAR)   NOT NULL,
    fecha_alta_utc        TIMESTAMP           NOT NULL,
    estado                NUMBER(1)           DEFAULT 2 NOT NULL,
    CONSTRAINT pk_contenedor           PRIMARY KEY (id_contenedor),
    CONSTRAINT uq_contenedor_qr        UNIQUE (identificador_qr),
    CONSTRAINT fk_contenedor_punto     FOREIGN KEY (id_punto_instalacion)
                                       REFERENCES punto_instalacion (id_punto_instalacion),
    CONSTRAINT ck_contenedor_nombre    CHECK (TRIM(nombre) IS NOT NULL AND nombre = TRIM(nombre) AND LENGTH(nombre) >= 2),
    -- Formato del parámetro start de Telegram: 16 a 64 caracteres de A-Z a-z 0-9 _ -.
    CONSTRAINT ck_contenedor_qr        CHECK (
        LENGTH(identificador_qr) >= 16
        AND TRANSLATE(identificador_qr,
                      '#ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_-', '#') IS NULL),
    CONSTRAINT ck_contenedor_estado    CHECK (estado IN (1, 2, 3))  -- EstadoContenedor
);

CREATE INDEX ix_contenedor_punto ON contenedor (id_punto_instalacion);

-- 7. CONTENEDOR_MATERIAL: materiales que admite cada caneca. Que exista la fila = admitido.
--    «Una caneca en servicio admite al menos un material» lo garantizan la entidad y la lógica.
CREATE TABLE contenedor_material (
    id_contenedor  NUMBER(10)  NOT NULL,
    id_material    NUMBER(10)  NOT NULL,
    CONSTRAINT pk_contenedor_material      PRIMARY KEY (id_contenedor, id_material),
    CONSTRAINT fk_cont_material_contenedor FOREIGN KEY (id_contenedor) REFERENCES contenedor (id_contenedor),
    CONSTRAINT fk_cont_material_material   FOREIGN KEY (id_material)   REFERENCES material (id_material)
);

-- Índice de la clave foránea a MATERIAL: «¿qué canecas reciben PET?».
CREATE INDEX ix_contenedor_material_mat ON contenedor_material (id_material);

-- 8. Comentarios en el diccionario de Oracle (visibles en SQL Developer, pestaña Detalles).
COMMENT ON TABLE rol                 IS 'Catálogo de roles aprobados: 1 Ciudadano, 2 Operario, 3 Administrador';
COMMENT ON TABLE usuario             IS 'Cuenta de una persona; sin contraseñas (van en otra tabla)';
COMMENT ON TABLE usuario_rol         IS 'Roles de cada usuario; una cuenta puede tener varios';
COMMENT ON TABLE material            IS 'Catálogo validado de materiales; incluye no admitidos para orientar';
COMMENT ON TABLE punto_instalacion   IS 'Lugar físico donde se instalan las canecas';
COMMENT ON TABLE contenedor          IS 'Caneca física de un compartimiento y su QR público';
COMMENT ON TABLE contenedor_material IS 'Materiales que admite cada caneca';
COMMENT ON COLUMN contenedor.identificador_qr IS 'Parámetro start del enlace de Telegram; público, no autoriza nada';
COMMENT ON COLUMN contenedor.estado           IS '1 EnServicio, 2 FueraDeServicio, 3 DadoDeBaja';
COMMENT ON COLUMN usuario_rol.fecha_asignacion_utc IS 'Metadato técnico; la evidencia de quién asignó el rol va en auditoría';
COMMENT ON COLUMN material.categoria          IS '1 Aprovechable, 2 OrganicoAprovechable, 3 NoAprovechable, 4 Peligroso';

BEGIN
    DBMS_OUTPUT.PUT_LINE('Tablas iniciales de EcoAccess P3 creadas.');
END;
/

WHENEVER SQLERROR CONTINUE
