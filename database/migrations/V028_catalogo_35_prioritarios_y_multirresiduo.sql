CREATE TABLE CATALOGO_PRIORITARIO_35 (
    CODIGO_35                   VARCHAR2(10)   NOT NULL,
    NOMBRE                      VARCHAR2(160)  NOT NULL,
    CATEGORIA_CANECA            VARCHAR2(20)   NOT NULL,
    CODIGO_MATERIAL_ORACLE      VARCHAR2(40)   NOT NULL,
    REQUIERE_VALIDACION_ESTADO  NUMBER(1)      DEFAULT 0 NOT NULL,
    ES_SANITARIO_SIMULADO       NUMBER(1)      DEFAULT 0 NOT NULL,
    VERSION_CATALOGO            VARCHAR2(30)   DEFAULT '2026.11.22-35' NOT NULL,
    ACTIVO                      NUMBER(1)      DEFAULT 1 NOT NULL,
    FECHA_ACTUALIZACION_UTC     TIMESTAMP(3)   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CATALOGO_PRIORITARIO_35 PRIMARY KEY (CODIGO_35),
    CONSTRAINT CK_CAT35_CANECA CHECK (CATEGORIA_CANECA IN ('VERDE', 'BLANCA', 'NEGRA')),
    CONSTRAINT CK_CAT35_FLAGS CHECK (REQUIERE_VALIDACION_ESTADO IN (0, 1) AND ES_SANITARIO_SIMULADO IN (0, 1) AND ACTIVO IN (0, 1))
);

CREATE TABLE REGISTRO_MULTIRRESIDUO (
    ID_REGISTRO_MULTI           NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CLAVE_IDEMPOTENCIA          VARCHAR2(100)  NOT NULL,
    FECHA_OPERACION_UTC         TIMESTAMP(3)   DEFAULT SYSTIMESTAMP NOT NULL,
    MODO_ORIGEN                 VARCHAR2(20)   NOT NULL,
    MODELO_VISION               VARCHAR2(80)   NULL,
    COMBINACION_CANECAS         VARCHAR2(40)   NOT NULL,
    CODIGOS_MATERIAL_35         VARCHAR2(400)  NULL,
    CANECAS_SOLICITADAS         VARCHAR2(60)   NULL,
    CANECAS_CONFIRMADAS         VARCHAR2(60)   NULL,
    ESTADO_OPERACION            VARCHAR2(40)   NOT NULL,
    ORIGEN_OFFLINE_SINC         NUMBER(1)      DEFAULT 0 NOT NULL,
    DETALLE                     VARCHAR2(500)  NULL,
    CONSTRAINT PK_REGISTRO_MULTIRRESIDUO PRIMARY KEY (ID_REGISTRO_MULTI),
    CONSTRAINT UQ_REGMULTI_IDEMPOTENCIA UNIQUE (CLAVE_IDEMPOTENCIA),
    CONSTRAINT CK_REGMULTI_ORIGEN CHECK (MODO_ORIGEN IN ('Visual', 'Manual', 'Mixto')),
    CONSTRAINT CK_REGMULTI_OFFLINE CHECK (ORIGEN_OFFLINE_SINC IN (0, 1))
);

CREATE INDEX IX_REGMULTI_FECHA ON REGISTRO_MULTIRRESIDUO (FECHA_OPERACION_UTC DESC);
CREATE INDEX IX_REGMULTI_COMBINACION ON REGISTRO_MULTIRRESIDUO (COMBINACION_CANECAS);

COMMENT ON TABLE CATALOGO_PRIORITARIO_35 IS 'Catálogo versionado de los 35 residuos prioritarios (10 verde, 13 blanca, 12 negra).';
COMMENT ON TABLE REGISTRO_MULTIRRESIDUO IS 'Auditoría idempotente de clasificaciones y aperturas multirresiduo sin datos personales innecesarios.';
